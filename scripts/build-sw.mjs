import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, resolve, sep } from "node:path";
import { pathToFileURL } from "node:url";

/**
 * Generates `sw.js` for the static build: LearnV installs as an app and opens offline.
 *
 * - Precache: the app shell (index.html), every JS/CSS chunk (lazy screens included, so a
 *   screen never visited online still opens offline), the manifest and the icons.
 * - Fonts and illustrations are cached the first time they are used, not up front: the
 *   Korean font alone ships more than a hundred subsets.
 * - The cache name carries a hash of the precached files, so each deploy replaces it and
 *   old chunks are dropped. No dependency: the worker is a few dozen lines.
 */
const PRECACHE = [/^index\.html$/, /^manifest\.webmanifest$/, /^favicon\.svg$/, /^icons\/.+\.png$/, /^assets\/.+\.(?:js|css)$/];

export function selectPrecache(files) {
  return files
    .map((file) => file.split(sep).join("/"))
    .filter((file) => PRECACHE.some((pattern) => pattern.test(file)))
    .sort();
}

export function cacheVersion(entries) {
  const hash = createHash("sha256");
  for (const { path, content } of entries) hash.update(path).update("\0").update(content);
  return hash.digest("hex").slice(0, 16);
}

export function serviceWorkerSource({ version, precache }) {
  return `/* LearnV service worker, generated by scripts/build-sw.mjs. Do not edit. */
const VERSION = ${JSON.stringify(version)};
const SHELL = "learnv-shell-" + VERSION;
const RUNTIME = "learnv-runtime";
const PRECACHE = ${JSON.stringify(precache)};
const scope = new URL(self.registration.scope);
const toUrl = (path) => new URL(path, scope).href;
const INDEX = toUrl("index.html");
// Module scripts are requested with an Origin header; a Vary: Origin response must still match.
const MATCH = { ignoreVary: true };

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(SHELL).then((cache) => cache.addAll(PRECACHE.map(toUrl))).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((key) => key.startsWith("learnv-shell-") && key !== SHELL).map((key) => caches.delete(key))))
    .then(() => self.clients.claim()));
});

function withTimeout(promise, ms) {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error("timeout")), ms);
    promise.then((value) => { clearTimeout(timer); resolve(value); }, (error) => { clearTimeout(timer); reject(error); });
  });
}

// Pages: the network first (a new deploy shows at once), the cached shell when offline.
async function page(request) {
  try {
    const response = await withTimeout(fetch(request), 4000);
    if (response.ok) (await caches.open(SHELL)).put(INDEX, response.clone());
    return response;
  } catch {
    return (await caches.match(INDEX, MATCH)) ?? Response.error();
  }
}

// Hashed chunks never change: the cache first.
async function hashed(request) {
  const cached = await caches.match(request, MATCH);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok) (await caches.open(SHELL)).put(request, response.clone());
  return response;
}

// Data (radar, catalogues): the network first, the last copy offline.
async function data(request) {
  try {
    const response = await fetch(request);
    if (response.ok) (await caches.open(RUNTIME)).put(request, response.clone());
    return response;
  } catch {
    return (await caches.match(request, MATCH)) ?? Response.error();
  }
}

// Illustrations, icons, fonts outside /assets: the cached copy at once, refreshed behind.
async function asset(request) {
  const cache = await caches.open(RUNTIME);
  const cached = await cache.match(request, MATCH);
  const network = fetch(request).then((response) => { if (response.ok) cache.put(request, response.clone()); return response; });
  if (cached) { network.catch(() => {}); return cached; }
  return network;
}

// The daily reminder: a tap brings an open LearnV window forward, or opens one.
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  event.waitUntil(self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((windows) => {
    const open = windows.find((client) => client.url.startsWith(scope.href));
    return open ? open.focus() : self.clients.openWindow(scope.href);
  }));
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return;
  // GitHub Pages nests the learning QA build under qa/: it has its own worker and shell.
  if (url.pathname.startsWith(scope.pathname + "qa/")) return;
  if (request.mode === "navigate") event.respondWith(page(request));
  else if (url.pathname.startsWith(scope.pathname + "assets/")) event.respondWith(hashed(request));
  else if (url.pathname.endsWith(".json")) event.respondWith(data(request));
  else event.respondWith(asset(request));
});
`;
}

async function listFiles(directory, root = directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? listFiles(path, root) : [relative(root, path)];
  }));
  return nested.flat();
}

export async function buildServiceWorker(directory) {
  const root = resolve(directory);
  const precache = selectPrecache(await listFiles(root));
  const entries = await Promise.all(precache.map(async (path) => ({ path, content: await readFile(join(root, path)) })));
  const version = cacheVersion(entries);
  await writeFile(join(root, "sw.js"), serviceWorkerSource({ version, precache }));
  return { version, files: precache.length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const { version, files } = await buildServiceWorker(process.argv[2] ?? "dist");
  console.log(`Service worker ${version}: ${files} file(s) precached.`);
}
